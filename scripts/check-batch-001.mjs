#!/usr/bin/env node
// Checks the deployed site's /batch/001 against the printed-jar record.
//
//   npm run check:batch-001                        production, https://lailark.in
//   npm run check:batch-001 -- --project staging    https://tree-quiz-74e04.web.app
//   npm run check:batch-001 -- --url http://127.0.0.1:5010   any base URL
//
// Compares the /batch/001 body byte for byte against the built site/out/batch/001.html
// (run `npm run build` first; M3.4 generates this page from site/content/batches/001.json)
// and checks /batch/1 and /batch/01 301-redirect to /batch/001 (no redirects
// followed; the Location header is read directly). Prints one line per check.
// Exit codes:
//   0 = all checks pass, site and repo match byte-for-byte
//   1 = D28 difference only (ingredient line with vs without percentages): deploy is owed
//   2 = other differences or redirect failures: unexpected drift, investigate before deploying

import { existsSync, readFileSync } from "node:fs";
import { argv, exit } from "node:process";
import { resolve } from "node:path";

const ROOT = resolve(new URL("..", import.meta.url).pathname);
// M3.4: /batch/001 is now generated by the site/app/batch/[nnn] route from
// site/content/batches/001.json (D48), so the record this script diffs
// against is the build output, not a hand-written file. Run `npm run
// build` (or `npm run build --workspace site`) first.
//
// `next build` with `output: "export"` and `trailingSlash: false` (this
// site's next.config.mjs, matching firebase.json's own `trailingSlash:
// false` and `cleanUrls: true`) writes a flat `<route>.html` file rather
// than `<route>/index.html`, so the built record is site/out/batch/001.html,
// not a nested index.html.
const RECORD_PATH = resolve(ROOT, "site/out/batch/001.html");
// Read the staging project id from .firebaserc rather than hard-coding it, so a
// future repoint is one file.
const FIREBASERC = JSON.parse(readFileSync(resolve(ROOT, ".firebaserc"), "utf8"));

function arg(name) {
  const i = argv.indexOf(`--${name}`);
  if (i === -1) return undefined;
  const v = argv[i + 1];
  return v && !v.startsWith("--") ? v : true;
}

function baseUrl() {
  const explicit = arg("url");
  if (explicit && explicit !== true) return explicit.replace(/\/$/, "");
  if (arg("project") === "staging") return `https://${FIREBASERC.projects.staging}.web.app`;
  return "https://lailark.in";
}

let exitCode = 0;

function report(name, ok, detail) {
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? `  — ${detail}` : ""}`);
  if (!ok && exitCode === 0) exitCode = 2;
}

function setExitCode(code) {
  if (code > exitCode) exitCode = code;
}

async function checkRecord(base) {
  const url = `${base}/batch/001`;
  if (!existsSync(RECORD_PATH)) {
    console.error(
      `Build output not found at ${RECORD_PATH}.\n` +
        `Run "npm run build" (or "npm run build --workspace site") first, then re-run this check.`,
    );
    setExitCode(2);
    exit(2);
    return;
  }
  const expected = readFileSync(RECORD_PATH);
  let res;
  try {
    res = await fetch(url, { redirect: "manual" });
  } catch (e) {
    report(`GET ${url}`, false, `request failed: ${e.message}`);
    return;
  }
  if (res.status !== 200) {
    report(`GET ${url}`, false, `expected 200, got ${res.status}`);
    return;
  }
  const actual = Buffer.from(await res.arrayBuffer());
  if (!actual.equals(expected)) {
    // Find and report the actual differing lines
    const actualStr = actual.toString("utf8");
    const expectedStr = expected.toString("utf8");
    const actualLines = actualStr.split("\n");
    const expectedLines = expectedStr.split("\n");

    report(
      `GET ${url}`,
      false,
      `body differs (${actual.length} bytes live vs ${expected.length} bytes repo)`,
    );

    // Find differing lines and show them
    const diffs = [];
    for (let i = 0; i < Math.max(actualLines.length, expectedLines.length); i++) {
      const actualLine = actualLines[i] ?? "";
      const expectedLine = expectedLines[i] ?? "";
      if (actualLine !== expectedLine) {
        diffs.push({ lineNum: i + 1, actual: actualLine, expected: expectedLine });
      }
    }

    // Show the differing lines
    if (diffs.length > 0) {
      console.log(`Differing content:\n`);
      diffs.forEach((d) => {
        console.log(`Line ${d.lineNum}:`);
        if (d.expected)
          console.log(`  Repo record:  ${d.expected.trim()}`);
        if (d.actual)
          console.log(`  Live site:    ${d.actual.trim()}`);
        console.log();
      });
    }

    // Check for D28 case: ingredient line with percentages stripped from live matches repo.
    // D28 defines the /batch/001 page as carrying the same ingredient list as the label,
    // without the two percentages. So strip percentage annotations from live and compare.
    const percentagePattern = /\s*\([0-9]+(?:\.[0-9]+)?%\)/g;
    let isD28Difference = diffs.length > 0; // Assume D28 if there are any diffs

    for (const diff of diffs) {
      const liveStripped = diff.actual.replace(percentagePattern, "");
      if (liveStripped !== diff.expected) {
        // This line differs even without percentages: not a D28 difference
        isD28Difference = false;
        break;
      }
    }

    // Determine which version to recommend and why
    const byteDiff = Math.abs(actual.length - expected.length);
    const repoLarger = expected.length > actual.length;

    if (isD28Difference) {
      console.log(
        `The repo is ahead: it has the correct D28 implementation (ingredient line without percentages). ` +
          `A deploy of the customer site is owed to bring it up to date.\n`
      );
      exitCode = 1; // D28 is expected, not an error
    } else if (repoLarger) {
      console.log(
        `The repo is likely ahead (${byteDiff} bytes smaller, suggesting newer content). ` +
          `A deploy of the customer site may be owed to bring it up to date.\n`
      );
    } else {
      console.log(
        `The live site has unexpected content (${byteDiff} bytes extra). ` +
        `This may mean an old version was deployed or the site was edited outside the normal process. ` +
        `Check the differences above and investigate before redeploying.\n`
      );
    }

    return;
  }
  report(`GET ${url}`, true, "200, byte-identical to the record");
}

async function checkRedirect(base, path) {
  const url = `${base}${path}`;
  let res;
  try {
    res = await fetch(url, { redirect: "manual" });
  } catch (e) {
    report(`GET ${url}`, false, `request failed: ${e.message}`);
    return;
  }
  if (res.status !== 301) {
    report(`GET ${url}`, false, `expected 301, got ${res.status}`);
    return;
  }
  const location = res.headers.get("location") ?? "";
  if (!location.endsWith("/batch/001")) {
    report(`GET ${url}`, false, `expected Location ending in /batch/001, got "${location}"`);
    return;
  }
  report(`GET ${url}`, true, `301 → ${location}`);
}

async function main() {
  const base = baseUrl();
  console.log(`checking ${base} ...\n`);
  await checkRecord(base);
  await checkRedirect(base, "/batch/1");
  await checkRedirect(base, "/batch/01");
  if (exitCode > 0) {
    if (exitCode === 1) {
      console.error("\nD28 difference found.");
    } else {
      console.error("\nfailed.");
    }
    exit(exitCode);
    return;
  }
  console.log("\nall good.");
  // fetch's keep-alive connection pool can otherwise hold the event loop open.
  exit(0);
}

main().catch((e) => {
  console.error(e);
  exit(2);
});
